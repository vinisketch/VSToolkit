import dts from 'rollup-plugin-dts';
import esbuild from 'rollup-plugin-esbuild';

// the libraries the ui uses, not bundled
const external = ['vs_utils', 'vs_ui_utils', 'vs_toolkit/vs_core'];

/**
 * The html templates of the components are imported as strings
 */
const html = {
  name: 'html',
  transform(code, id) {
    if (!id.endsWith('.html')) return null;
    return { code: `export default ${JSON.stringify(code)};`, map: { mappings: '' } };
  },
};

export default [{
    external,
    input: 'src/ui/index.ts',
    plugins: [html, esbuild({
      include: /\.[jt]sx?$/,
      exclude: /node_modules/,
      sourceMap: true,
      tsconfig: 'src/tsconfig.ui.json'
    })],
    output: [
      {
        file: 'dist/vs_ui.es.js',
        format: 'es',
        sourcemap: true,
        exports: 'named',
      },
      {
        file: 'dist/vs_ui.amd.js',
        format: 'amd',
        sourcemap: true,
        name: 'vs_ui',
        exports: 'named',
      },
    ],
  },
  {
    // the declarations generated by tsc:ui
    external,
    input: 'build/ui/index.d.ts',
    plugins: [dts()],
    output: {
      file: 'dist/vs_ui.d.ts',
      format: 'es',
    },
  }
]
